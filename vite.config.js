import { defineConfig } from 'vite';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

// In production builds, drop the dev-server websocket from the CSP so the
// app cannot open any network connection at all.
const lockDownCsp = {
  name: 'lock-down-csp',
  apply: 'build',
  transformIndexHtml: (html) => html.replace(' ws:', ''),
};

// Writes dist/sw.js: a service worker that keeps every app file (including
// the OCR engine) so the installed web app works offline. Only used when the
// app runs as a website, e.g. installed on a Chromebook.
const offlineCache = {
  name: 'offline-cache',
  apply: 'build',
  closeBundle() {
    const dist = 'dist';
    const files = [];
    const walk = (dir) => {
      for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const path = join(dir, entry.name);
        if (entry.isDirectory()) walk(path);
        else if (entry.name !== 'sw.js' && !entry.name.endsWith('.map')) files.push(relative(dist, path).split('\\').join('/'));
      }
    };
    walk(dist);
    files.sort();
    const hash = createHash('sha256');
    for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
    const version = hash.digest('hex').slice(0, 12);
    writeFileSync(join(dist, 'sw.js'), `// Generated by vite.config.js: keeps Plain Office working offline.
const CACHE = 'plain-office-${version}';
const FILES = ${JSON.stringify(['./', ...files.map((f) => `./${f}`)], null, 0)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

// A new version takes over the next time the app is opened, so an open window never mixes versions.
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(
    keys.filter((key) => key.startsWith('plain-office-') && key !== CACHE).map((key) => caches.delete(key)),
  )));
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith((async () => {
    const hit = await caches.match(request, { ignoreSearch: true, ignoreVary: true });
    if (hit) return hit;
    try {
      return await fetch(request);
    } catch (err) {
      if (request.mode === 'navigate') return caches.match('./index.html');
      throw err;
    }
  })());
});
`);
  },
};

export default defineConfig({
  base: './',
  plugins: [lockDownCsp, offlineCache],
  // Pre-bundle the lazily loaded libraries so the dev server never reloads mid-session.
  optimizeDeps: {
    include: ['mammoth', 'docx', 'xlsx', 'jszip', 'pptxgenjs', 'pdf-lib', 'pdfjs-dist/legacy/build/pdf.mjs', 'jspdf', 'html2canvas', 'tesseract.js', 'wasm-feature-detect'],
  },
  build: {
    target: 'es2020',
    chunkSizeWarningLimit: 3000,
  },
});
